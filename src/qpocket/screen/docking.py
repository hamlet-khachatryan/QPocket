"""Job CSV and submission script generation for AutoDock Vina / QuickVina.

Public API:
- ``parse_vina_box(vina_box_txt)`` → dict
- ``generate_docking_jobs_csv(...)`` → pd.DataFrame
- ``write_local_script(...)``
- ``write_slurm_script(...)``
"""
from __future__ import annotations

from pathlib import Path
from typing import Dict, List

import pandas as pd
from eliot import log_message

from qpocket.screen.config import DockingConfig, SlurmConfig


# ---------------------------------------------------------------------------
# Box parameter parsing
# ---------------------------------------------------------------------------

def parse_vina_box(vina_box_txt: Path) -> Dict[str, float]:
    """Parse a Vina-style ``vina_box.txt`` file.

    Expected line format: ``key = value``

    Args:
        vina_box_txt: Path to the box config file.

    Returns:
        Dict with keys ``center_x/y/z``, ``size_x/y/z``,
        ``exhaustiveness``, ``num_modes``, ``energy_range``.
    """
    params: Dict[str, float] = {}
    with open(vina_box_txt) as fh:
        for line in fh:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            if "=" in line:
                key, _, val = line.partition("=")
                try:
                    params[key.strip()] = float(val.strip())
                except ValueError:
                    pass
    return params


# ---------------------------------------------------------------------------
# Job CSV
# ---------------------------------------------------------------------------

def generate_docking_jobs_csv(
    proteins: List[Path],
    ligands: Dict[str, List[Path]],
    box_params: Dict[str, float],
    results_dir: Path,
    docking_cfg: DockingConfig,
) -> pd.DataFrame:
    """Build a docking jobs DataFrame.

    Each row describes one docking run (one protein × one ligand).

    Args:
        proteins: List of protein PDBQT paths.
        ligands: Dict with keys ``"actives"`` and optionally ``"decoys"``,
            each a list of ligand PDBQT paths.
        box_params: Parsed box parameters from :func:`parse_vina_box`.
        results_dir: Directory in which output PDBQT files will be placed.
        docking_cfg: :class:`~qpocket.screen.config.DockingConfig`.

    Returns:
        DataFrame with columns: job_id, protein_pdbqt, ligand_pdbqt,
        output_pdbqt, center_x/y/z, size_x/y/z, exhaustiveness,
        num_modes, energy_range, molecule_type, pdb_id, ligand_id.
    """
    results_dir.mkdir(parents=True, exist_ok=True)

    rows = []
    job_idx = 0

    for mol_type, lig_list in ligands.items():
        for lig_path in lig_list:
            lig_id = lig_path.stem
            for prot_path in proteins:
                pdb_id = prot_path.stem
                job_id = f"job_{job_idx:05d}"
                out_pdbqt = results_dir / f"{job_id}_out.pdbqt"

                rows.append(
                    {
                        "job_id": job_id,
                        "protein_pdbqt": str(prot_path),
                        "ligand_pdbqt": str(lig_path),
                        "output_pdbqt": str(out_pdbqt),
                        "center_x": box_params.get("center_x", 0.0),
                        "center_y": box_params.get("center_y", 0.0),
                        "center_z": box_params.get("center_z", 0.0),
                        "size_x": box_params.get("size_x", 20.0),
                        "size_y": box_params.get("size_y", 20.0),
                        "size_z": box_params.get("size_z", 20.0),
                        "exhaustiveness": int(docking_cfg.exhaustiveness),
                        "num_modes": int(docking_cfg.num_modes),
                        "energy_range": docking_cfg.energy_range,
                        "molecule_type": mol_type,
                        "pdb_id": pdb_id,
                        "ligand_id": lig_id,
                    }
                )
                job_idx += 1

    df = pd.DataFrame(rows)
    log_message(message_type="docking_jobs_created", n_jobs=len(df))
    return df


