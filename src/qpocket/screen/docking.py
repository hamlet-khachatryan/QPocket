def write_local_script(
    jobs_csv_path: Path,
    docking_cfg: DockingConfig,
    output_path: Path,
) -> None:
    """Write a bash script that runs all docking jobs locally.

    Uses GNU ``parallel`` when available; falls back to a sequential
    ``for`` loop otherwise.

    Args:
        jobs_csv_path: Path to ``docking_jobs.csv``.
        docking_cfg: Docking engine config.
        output_path: Path for the output ``.sh`` file.
    """
    engine = docking_cfg.engine_path
    cpus = docking_cfg.cpus

    script = f"""#!/usr/bin/env bash
# QPocket docking script — generated by qpocket-screen
# Engine: {docking_cfg.engine}
set -euo pipefail

JOBS_CSV="{jobs_csv_path}"
ENGINE="{engine}"
CPUS={cpus}

_run_job() {{
    local row="$1"
    local job_id    protein_pdbqt ligand_pdbqt output_pdbqt
    local center_x  center_y      center_z
    local size_x    size_y        size_z
    local exhaustiveness num_modes energy_range

    IFS=',' read -r job_id protein_pdbqt ligand_pdbqt output_pdbqt \\
        center_x center_y center_z size_x size_y size_z \\
        exhaustiveness num_modes energy_range \\
        molecule_type pdb_id ligand_id <<< "$row"

    mkdir -p "$(dirname "$output_pdbqt")"

    "$ENGINE" \\
        --receptor "$protein_pdbqt" \\
        --ligand   "$ligand_pdbqt"  \\
        --out      "$output_pdbqt"  \\
        --center_x "$center_x" --center_y "$center_y" --center_z "$center_z" \\
        --size_x   "$size_x"   --size_y   "$size_y"   --size_z   "$size_z"   \\
        --exhaustiveness "$exhaustiveness" \\
        --num_modes      "$num_modes"      \\
        --energy_range   "$energy_range"   \\
        --cpu            "$CPUS"
}}

export -f _run_job
export ENGINE CPUS

if command -v parallel &>/dev/null; then
    tail -n +2 "$JOBS_CSV" | parallel -j "$CPUS" _run_job {{}}
else
    while IFS= read -r row; do
        _run_job "$row"
    done < <(tail -n +2 "$JOBS_CSV")
fi

echo "All docking jobs completed."
"""

    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w") as fh:
        fh.write(script)
    output_path.chmod(0o755)
    log_message(message_type="local_script_written", path=str(output_path))


def write_slurm_script(
    jobs_csv_path: Path,
    docking_cfg: DockingConfig,
    slurm_cfg: SlurmConfig,
    output_path: Path,
) -> None:
    """Write a SLURM array job script for all docking jobs.

    Each array task reads its row from the CSV using ``awk`` and runs one
    Vina/QuickVina call.

    Args:
        jobs_csv_path: Path to ``docking_jobs.csv``.
        docking_cfg: Docking engine config.
        slurm_cfg: SLURM resource config.
        output_path: Path for the output ``.slurm`` file.
    """
    # Count data rows (excluding header)
    try:
        n_jobs = sum(1 for _ in open(jobs_csv_path)) - 1
    except FileNotFoundError:
        n_jobs = 1  # placeholder if CSV not yet written

    engine = docking_cfg.engine_path
    max_conc = slurm_cfg.max_concurrent

    script = f"""#!/usr/bin/env bash
#SBATCH --job-name=qpocket_screen
#SBATCH --partition={slurm_cfg.partition}
#SBATCH --cpus-per-task={slurm_cfg.cpus_per_task}
#SBATCH --mem={slurm_cfg.mem}
#SBATCH --time={slurm_cfg.time}
#SBATCH --array=1-{n_jobs}%{max_conc}
#SBATCH --output=slurm_%A_%a.out
#SBATCH --error=slurm_%A_%a.err

# QPocket SLURM docking script — generated by qpocket-screen
# Engine: {docking_cfg.engine}

JOBS_CSV="{jobs_csv_path}"
ENGINE="{engine}"

# awk "NR==n" selects row n; array tasks are 1-indexed; header is row 1
ROW=$(awk "NR==$(( SLURM_ARRAY_TASK_ID + 1 ))" "$JOBS_CSV")

IFS=',' read -r job_id protein_pdbqt ligand_pdbqt output_pdbqt \\
    center_x center_y center_z size_x size_y size_z \\
    exhaustiveness num_modes energy_range \\
    molecule_type pdb_id ligand_id <<< "$ROW"

mkdir -p "$(dirname "$output_pdbqt")"

"$ENGINE" \\
    --receptor "$protein_pdbqt" \\
    --ligand   "$ligand_pdbqt"  \\
    --out      "$output_pdbqt"  \\
    --center_x "$center_x" --center_y "$center_y" --center_z "$center_z" \\
    --size_x   "$size_x"   --size_y   "$size_y"   --size_z   "$size_z"   \\
    --exhaustiveness "$exhaustiveness" \\
    --num_modes      "$num_modes"      \\
    --energy_range   "$energy_range"   \\
    --cpu            "$SLURM_CPUS_PER_TASK"

echo "Job $job_id ($pdb_id x $ligand_id) done."
"""

    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w") as fh:
        fh.write(script)
    output_path.chmod(0o755)
    log_message(message_type="slurm_script_written", path=str(output_path), n_jobs=n_jobs)
